"""Published Countertrend identifiers, independent of UI filters and qualification.

Consumes the already approved Countertrend relationship sets. Never calculates W,
changes membership or borrows Directional export placement.
"""
import re
from ..tradingview import resolve

FILENAMES = {
    'short': {'resilient':'Resilient.txt', 'snapback':'Snapback.txt'},
    'long': {'resilient':'Strong-Leaders.txt', 'snapback':'Relative-Weakness.txt'},
}
COMBINED = 'Countertrend.txt'
IDENTIFIER = re.compile(r'[A-Z0-9_]+:[A-Z0-9_.-]+\Z')


def exports(snapshot, mapping):
    ct = snapshot.get('research', {}).get('countertrend', {})
    side = ct.get('side')
    empty = {'available':False, 'side':side, 'files':{}, 'symbols':{}}
    if not ct.get('available') or side not in FILENAMES:
        return empty
    known = {(row['ticker'], row['theme_id']) for row in snapshot.get('relationships', ())}
    buckets = {}
    for key in ('resilient', 'snapback'):
        rows = ct.get('buckets', {}).get(key, {}).get('rows', ())
        if any((row['ticker'], row['theme_id']) not in known for row in rows):
            raise ValueError('Countertrend export relationship unavailable')
        # Keep the supplied W ordering; first occurrence chooses each stock.
        buckets[key] = list(dict.fromkeys(row['ticker'] for row in rows))
    tickers = sorted(set().union(*buckets.values()))
    if not tickers:
        return empty
    symbols = {ticker:resolve(ticker, mapping) for ticker in tickers}
    if any(not IDENTIFIER.fullmatch(value) for value in symbols.values()):
        raise ValueError('Invalid Countertrend TradingView identifier')
    if len(set(symbols.values())) != len(symbols):
        raise ValueError('Distinct Countertrend tickers resolve to one identifier')
    def text(names):
        return ''.join(symbols[ticker]+'\n' for ticker in names)
    files = {COMBINED:text(tickers)}
    files.update({FILENAMES[side][key]:text(names) for key,names in buckets.items()})
    return {'available':True, 'side':side, 'files':files, 'symbols':symbols}


def attach(snapshot, mapping):
    result = dict(snapshot)
    result['research'] = dict(snapshot['research'])
    result['research']['countertrend'] = dict(snapshot['research']['countertrend'])
    result['research']['countertrend']['exports'] = exports(snapshot, mapping)
    return result


def public_exports(ct):
    """Validate exact sets before projecting only safe published TXT content.

    Verified identifiers are generated by the backend; no venue inference here.
    Public output needs files, not the internal verification lookup.
    """
    published = ct.get('exports')
    if published is None:
        return None  # Older snapshots stay readable, without inventing exports.
    if not isinstance(published, dict) or type(published.get('available')) is not bool:
        raise ValueError('Invalid Countertrend export contract')
    side = published.get('side')
    files, symbols = published.get('files'), published.get('symbols')
    if not isinstance(files, dict) or not isinstance(symbols, dict):
        raise ValueError('Invalid Countertrend export files')
    if not published['available']:
        if files or symbols:
            raise ValueError('Unavailable Countertrend contains exports')
        return {'available':False, 'side':side, 'files':{}}
    if not ct.get('available') or side != ct.get('side') or side not in FILENAMES:
        raise ValueError('Countertrend export side differs from published lens')
    expected = {COMBINED, *FILENAMES[side].values()}
    if set(files) != expected:
        raise ValueError('Countertrend export filenames differ from published lens')
    buckets = {key:list(dict.fromkeys(row['ticker'] for row in ct['buckets'][key]['rows'])) for key in FILENAMES[side]}
    tickers = sorted(set().union(*buckets.values()))
    if not tickers or set(symbols) != set(tickers) or any(not isinstance(value,str) or not IDENTIFIER.fullmatch(value) for value in symbols.values()) or len(set(symbols.values())) != len(symbols):
        raise ValueError('Countertrend export identifiers differ from published lens')
    wanted = {COMBINED:tickers, **{FILENAMES[side][key]:names for key,names in buckets.items()}}
    if any(files[name] != ''.join(symbols[ticker]+'\n' for ticker in names) for name,names in wanted.items()):
        raise ValueError('Countertrend export contents differ from published lens')
    return {'available':True, 'side':side, 'files':dict(files)}
